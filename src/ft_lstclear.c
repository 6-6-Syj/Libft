#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*tmp;

	if (!lst || !del)
		return ;
	tmp = *lst;
	while (*lst != NULL)
	{
		tmp = tmp->next;
		ft_delete_node(*lst, del);
		*lst = tmp;
	}
}
